const ENDINGS = '(?:а|у|ом|е|ы|ов|ам|ами|ах|я|ю|ем|ием|ий|ия|ии|ого|ому|ым|ыми|ых|ые|го)?';
const KEYS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
const PATTERNS = KEYS.map(key => key.split(' ').map(word => {
    const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (/^[A-Za-z0-9-]+$/.test(word)) return escaped;
    const stem = word.endsWith('ие') || word.endsWith('ое')
        ? escaped.slice(0, -1)
        : word.endsWith('ый') ? escaped.slice(0, -2) : escaped;
    return stem === escaped ? escaped + ENDINGS : `(?:${escaped}|${stem}${ENDINGS})`;
}).join('\\s+'));
const TERM_RE = new RegExp(`(?<![\\p{L}\\p{N}])(${PATTERNS.join('|')})(?![\\p{L}\\p{N}])`, 'giu');

function escapeHtml(value) {
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function canonicalKey(match) {
    const words = match.toLowerCase().split(/\s+/);
    return KEYS.find(key => {
        const parts = key.toLowerCase().split(' ');
        if (parts.length !== words.length) return false;
        return parts.every((part, i) => {
            const stem = (part.endsWith('ие') || part.endsWith('ое'))
                ? part.slice(0, -1)
                : part.endsWith('ый') ? part.slice(0, -2) : part;
            return words[i] === part || words[i].startsWith(stem);
        });
    }) || null;
}

export function linkTerms(text) {
    const source = String(text === undefined || text === null ? '' : text);
    let out = '';
    let last = 0;
    for (const match of source.matchAll(TERM_RE)) {
        const key = canonicalKey(match[0]);
        if (!key) continue;
        out += escapeHtml(source.slice(last, match.index));
        out += `<span class="term-link" data-term="${escapeHtml(key)}" role="button" tabindex="0">${escapeHtml(match[0])}</span>`;
        last = match.index + match[0].length;
    }
    return out + escapeHtml(source.slice(last));
}
