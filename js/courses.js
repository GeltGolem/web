function course(modules, intro, lang = '') {
    return modules.map((m, id) => ({
        id,
        title: m.title,
        icon: m.icon,
        color: m.color,
        colorDark: m.colorDark,
        desc: m.desc,
        xpReward: m.xpReward,
        rewardOutfitIdx: -1,
        introLesson: id === 0 && intro ? { ...intro, intro: intro.intro || intro.title + '.' } : undefined,
        lessons: m.lessons.map(l => {
            const notes = DEEP_NOTES[lang] || {};
            const note = notes[`${id}:${l.title}`] || notes[l.title];
            const deep = id >= 3 && note ? ' ' + note : '';
            const theory = (l.theory || (l.note && !l.note.includes('?') ? l.note : '')) + deep;
            const questions = [];
            if (l.q) questions.push(mcq(l.q, l.opts, l.correct, l.exp, l.note || '', l.code || '', theory));
            if (!l.practice && l.opts) l.practice = P('Собери выражение.', '________', String(l.opts[l.correct]), l.opts, l.exp);
            const firstTheory = theory.split('. ')[0];
            const expLead = String(l.exp || '').split('. ')[0];
            let lead = String(l.intro || expLead || l.title).trim();
            const at = firstTheory.length > 8 ? lead.indexOf(firstTheory) : -1;
            if (at >= 0) lead = (lead.slice(0, at) + lead.slice(at + firstTheory.length)).replace(/\s+/g, ' ').trim();
            if (!lead || lead === l.title) lead = String(l.title) + '.';
            return { title: l.title, questions, practice: l.practice, intro: lead.endsWith('.') ? lead : lead + '.' };
        }),
        trophyQuestions: m.trophy,
    }));
}

