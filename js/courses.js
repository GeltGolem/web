// Каждый язык: 5 модулей по 10 уроков, финальный тест и подготовительный урок
// в первом модуле. Данные вынесены отдельно от игровой логики main.js.
//
// L  — урок: заголовок, подсказка, код, вопрос, варианты, индекс верного, объяснение,
//      необязательное практическое задание.
// P  — практика: допиши строку кода.
// T  — вопрос финального теста с вводом строки.
// course() собирает модули и проставляет id / награды / подготовительный урок.

const mcq = (q, opts, correct, exp, note = '', code = '', theory = '') => ({ q, opts, correct, exp, note, code, theory });
const practice = (q, starter, answer, chips, exp, note = '', code = '', theory = '') => ({
    type: 'practice', q, starter, answer, chips, exp, note, code, theory
});
const L = (title, note, code, q, opts, correct, exp, task, theory = '') => ({ title, note, code, q, opts, correct, exp, practice: task, theory });
const P = (q, starter, answer, chips, exp, note = '', code = '', theory = '') => practice(q, starter, answer, chips, exp, note, code, theory);
const T = (q, answer, chips, exp, code = '', accept = []) => ({ type: 'type', q, code, answer, chips, exp, accept });
const TP = (q, starter, answer, chips, exp, accept = []) => ({
    type: 'practice', q, code: starter, starter, answer, chips, exp, accept, caseSensitive: true
});

function course(modules, intro) {
    return modules.map((m, id) => ({
        id,
        title: m.title,
        icon: m.icon,
        color: m.color,
        colorDark: m.colorDark,
        desc: m.desc,
        xpReward: m.xpReward,
        rewardOutfitIdx: -1,
        introLesson: id === 0 && intro ? intro : undefined,
        lessons: m.lessons.map(l => {
            const questions = [];
            if (l.q) questions.push(mcq(l.q, l.opts, l.correct, l.exp, l.note || '', l.code || '', l.theory || ''));
            // Практика лежит отдельным полем урока, как в Pascal: startLesson
            // сам решает, поставить её в конец или в начало для уровня "Шарю".
            return { title: l.title, questions, practice: l.practice };
        }),
        trophyQuestions: m.trophy,
    }));
}

